import assert from 'node:assert/strict';
import { setTimeout as delay } from 'node:timers/promises';

export async function verifyNativeProfile({ adb, tap, find, nodes, screenshot, hideKeyboard,
  longPress, scale, sent, reply, restart, failDelete }) {
  const profile = '查看 bob 的资料';
  const direct = '与 bob 私聊';
  await tap('群聊'); await tap('消息'); await adb('shell', 'input', 'text', 'group-draft'); await hideKeyboard();
  await tap(profile); await find('个人资料'); await find('发消息'); await find('删除');
  await screenshot(`profile-${scale}`); await tap('返回'); await find('group-draft');
  await tap('添加内容'); await tap('历史记录'); await tap(profile);
  await find('个人资料'); await tap('返回'); await find('搜索消息或账户');
  await tap(profile); await tap('发消息'); await find('消息');
  await tap('消息'); await adb('shell', 'input', 'text', 'old-opening'); await tap('发送');
  reply('旧私聊回复'); await find('旧私聊回复'); await hideKeyboard();
  await tap('返回聊天列表'); await find(direct);
  await longPress(direct); await find('删除'); await screenshot(`profile-menu-${scale}`);
  await tap('删除'); await find('删除这段私聊？'); await tap('取消');
  const row = await find(direct);
  const [left, top, right, bottom] = [...row.bounds.matchAll(/\d+/g)].map(value => Number(value[0]));
  const x = Math.round(left + (right - left) * .15); const y = Math.round((top + bottom) / 2);
  await adb('shell', 'input', 'swipe', String(x), String(y), String(x + 240), String(y), '300');
  await find('删除'); await screenshot(`profile-swipe-${scale}`);
  await tap('删除'); await find('删除这段私聊？');
  failDelete(true); await tap('删除'); await find('删除失败，请稍后重试。');
  await screenshot(`profile-delete-error-${scale}`); await tap('取消'); failDelete(false);
  await tap(direct); await tap(profile); await tap('删除'); await find('删除这段私聊？');
  await screenshot(`profile-delete-confirm-${scale}`); await tap('删除'); await find('搜索聊天');
  assert.ok(!(await nodes()).some(node => node['content-desc'] === direct), 'Profile deletion removes the row');
  await restart();
  assert.ok(!(await nodes()).some(node => node['content-desc'] === direct), 'Restart must not restore the deleted contact');
  await tap('群聊'); await tap(profile); await tap('发消息');
  assert.ok(!(await nodes()).some(node => node.text === '旧私聊回复'), 'Deleted messages are absent');
  await tap('消息'); await adb('shell', 'input', 'text', 'fresh-opening'); await tap('发送');
  await delay(500); const count = sent.length;
  assert.equal(sent.at(-1).text, 'fresh-opening');
  await tap('消息'); await adb('shell', 'input', 'text', 'waiting-for-reply'); await tap('发送');
  await find('对方回复后才能继续发送。'); assert.equal(sent.length, count);
  await hideKeyboard(); await screenshot(`profile-fresh-limit-${scale}`);
  reply('新私聊回复'); await find('新私聊回复'); await tap('发送'); await delay(500);
  assert.equal(sent.length, count + 1); await hideKeyboard();
  await tap('返回聊天列表');
  const freshRow = await find(direct);
  const [, freshTop, , freshBottom] = [...freshRow.bounds.matchAll(/\d+/g)].map(value => Number(value[0]));
  const freshY = String(Math.round((freshTop + freshBottom) / 2));
  await adb('shell', 'input', 'swipe', String(x), freshY, String(x + 240), freshY, '300');
  await tap('删除'); await find('删除这段私聊？'); await tap('删除'); await find('搜索聊天');
  assert.ok(!(await nodes()).some(node => node['content-desc'] === direct), 'Swipe deletion removes the row');
  await screenshot(`profile-deleted-${scale}`);
  console.log(`PASS native profile, swipe/delete, restart and fresh exchange at font scale ${scale}`);
}
